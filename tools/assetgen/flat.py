def ring(size, r_out, r_in, fill, edge, alpha=255, ticks=0):
    im = Image.new("RGBA", (size, size))
    a = np.zeros((size, size, 4), np.uint8)
    y, x = np.mgrid[0:size, 0:size]
    c = size / 2
    r = np.hypot(x + 0.5 - c, y + 0.5 - c)
    body = (r <= r_out) & (r >= r_in)
    a[body, :3] = hexc(fill)
    a[body, 3] = alpha
    border = body & ((r > r_out - 1.5) | (r < r_in + 1.5))
    a[border, :3] = hexc(edge)
    a[border, 3] = 255
    if ticks:
        ang = np.arctan2(y + 0.5 - c, x + 0.5 - c)
        for k in range(ticks):
            t = k * math.tau / ticks
            m = (np.abs(np.angle(np.exp(1j * (ang - t)))) < 0.06) & (r > r_out - 7) & (r < r_out - 3)
            a[m, :3] = hexc("#ffe9a8")
            a[m, 3] = 255
    return Image.fromarray(a, "RGBA")


def disc(size, light, base, shade, edge):
    a = np.zeros((size, size, 4), np.uint8)
    y, x = np.mgrid[0:size, 0:size]
    c = size / 2
    r = np.hypot(x + 0.5 - c, y + 0.5 - c)
    inside = r <= c - 1
    # yukarı-solda ışık
    lx, ly = (x + 0.5 - c) / c, (y + 0.5 - c) / c
    lam = -(lx * 0.6 + ly * 0.8)
    tone = np.where(lam > 0.35, 0, np.where(lam > -0.35, 1, 2))
    cols = np.array([hexc(light), hexc(base), hexc(shade)], np.uint8)
    a[inside, :3] = cols[tone[inside]]
    a[inside, 3] = 255
    # parlama
    hl = (np.hypot(x + 0.5 - c * 0.65, y + 0.5 - c * 0.6) < c * 0.16) & inside
    a[hl, :3] = (255, 255, 255)
    rim = inside & (r > c - 2.5)
    a[rim, :3] = hexc(edge)
    return Image.fromarray(a, "RGBA")


def nine_patch(w, h, fill, light, shadow_c, edge, radius=3):
    """Pixel panel/tuş: koyu çerçeve, üstte açık çizgi, altta 2px gölge."""
    a = np.zeros((h, w, 4), np.uint8)
    y, x = np.mgrid[0:h, 0:w]
    inside = np.ones((h, w), bool)
    for cy, cx in ((0, 0), (0, w - 1), (h - 1, 0), (h - 1, w - 1)):
        dy = np.abs(y - cy)
        dx = np.abs(x - cx)
        inside &= ~((dy + dx) < radius - 1)
    a[inside, :3] = hexc(fill)
    a[inside, 3] = 255
    a[inside & (y >= h - 4), :3] = hexc(shadow_c)
    a[inside & (y >= 2) & (y <= 3), :3] = hexc(light)
    # kenar
    grow = np.zeros_like(inside)
    for dy, dx in ((0, 1), (1, 0), (0, -1), (-1, 0)):
        grow |= ~np.roll(np.roll(np.pad(inside, 1), dy, 0), dx, 1)[1:-1, 1:-1]
    border = inside & grow
    border |= inside & ((x == 0) | (y == 0) | (x == w - 1) | (y == h - 1))
    a[border, :3] = hexc(edge)
    return Image.fromarray(a, "RGBA")


