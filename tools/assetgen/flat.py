"""2D pixel üreticiler: zemin karoları, ot/çiçek, gölge, arayüz parçaları, ikonlar."""
import math
import random
import numpy as np
from PIL import Image, ImageDraw
from sdf import hexc

GRASS = ["#b6e36b", "#9bd35a", "#7fc44a", "#67b043", "#4f9a3a", "#2f6b33"]
DIRT = ["#d9a066", "#c48c58", "#b07848", "#966240", "#7d5233"]
PATH = ["#e3b97c", "#d9a066", "#c99360", "#b07848"]


def periodic_noise(size, seed, octaves=((4, 1.0), (8, 0.5), (16, 0.25))):
    """Kenarları birbirine uyan (dikişsiz) gürültü."""
    rng = np.random.default_rng(seed)
    y, x = np.mgrid[0:size, 0:size] / size * math.tau
    n = np.zeros((size, size))
    for freq, amp in octaves:
        for _ in range(3):
            fx, fy = rng.integers(-freq, freq + 1, 2)
            ph = rng.uniform(0, math.tau)
            n += amp * np.sin(fx * x + fy * y + ph)
    n -= n.min()
    return n / max(n.max(), 1e-9)


def quantize(n, colors, bayer=True):
    pal = np.array([hexc(c) for c in colors], np.uint8)
    k = len(colors)
    if bayer:
        b = np.array([[0, 8, 2, 10], [12, 4, 14, 6], [3, 11, 1, 9], [15, 7, 13, 5]]) / 16.0 - 0.5
        h, w = n.shape
        n = n + np.tile(b, (h // 4 + 1, w // 4 + 1))[:h, :w] * (0.6 / k)
    idx = np.clip((n * k).astype(int), 0, k - 1)
    return pal[idx]


def grass_tile(seed, flowers=False, dark=False):
    s = 32
    n = periodic_noise(s, seed)
    cols = GRASS[2:6] if dark else GRASS[0:5]
    n = 0.25 + n * 0.55
    img = quantize(n, cols[::-1])
    rng = random.Random(seed)
    # ot yaprakları: 2 pikselli dikey çizgiler (açık uç, koyu dip)
    for _ in range(22):
        x, y = rng.randrange(s), rng.randrange(s)
        img[y % s, x % s] = hexc(GRASS[0] if not dark else GRASS[2])
        img[(y + 1) % s, x % s] = hexc(GRASS[4] if not dark else GRASS[5])
    if flowers:
        for _ in range(3):
            x, y = rng.randrange(1, s - 1), rng.randrange(1, s - 1)
            c = hexc(rng.choice(["#ffffff", "#ffd25e", "#e04848", "#5ee0ff", "#f49ac1"]))
            for dx, dy in ((0, -1), (-1, 0), (1, 0), (0, 1)):
                img[y + dy, x + dx] = c
            img[y, x] = hexc("#ffd25e") if c != hexc("#ffd25e") else hexc("#e8a93a")
    return img


def dirt_tile(seed, path=False):
    s = 32
    n = periodic_noise(s, seed)
    img = quantize(n, (PATH if path else DIRT)[::-1])
    rng = random.Random(seed)
    for _ in range(6):  # çakıl
        x, y = rng.randrange(s - 1), rng.randrange(s - 1)
        img[y, x] = hexc("#c9c9c9")
        img[y + 1, x] = hexc("#6c6c7c")
    return img


def tileset():
    tiles = [grass_tile(i) for i in range(4)] + [grass_tile(10 + i, flowers=True) for i in range(4)] \
        + [grass_tile(20 + i, dark=True) for i in range(2)] + [dirt_tile(30 + i) for i in range(3)] \
        + [dirt_tile(40 + i, path=True) for i in range(3)]
    sheet = np.zeros((32 * 2, 32 * 8, 3), np.uint8)
    for i, t in enumerate(tiles):
        r, c = divmod(i, 8)
        sheet[r * 32:(r + 1) * 32, c * 32:(c + 1) * 32] = t
    names = ["grass0", "grass1", "grass2", "grass3", "flowers0", "flowers1", "flowers2", "flowers3",
             "dgrass0", "dgrass1", "dirt0", "dirt1", "dirt2", "path0", "path1", "path2"]
    return Image.fromarray(sheet, "RGB"), names


def dirt_patch(seed, w=64, h=40):
    """Çim üstüne serilen düzensiz toprak lekesi (kenarları çimle karışık)."""
    rng = np.random.default_rng(seed)
    y, x = np.mgrid[0:h, 0:w]
    cx, cy = w / 2, h / 2
    ang = np.arctan2(y - cy, x - cx)
    r = np.hypot((x - cx) / (w / 2), (y - cy) / (h / 2))
    wob = 0.78 + 0.12 * np.sin(ang * 3 + rng.uniform(0, 6)) + 0.08 * np.sin(ang * 7 + rng.uniform(0, 6))
    inside = r < wob
    n = periodic_noise(max(w, h), seed)[:h, :w]
    col = quantize(n, DIRT[::-1])
    out = np.zeros((h, w, 4), np.uint8)
    out[..., :3] = col
    out[..., 3] = np.where(inside, 255, 0)
    edge = inside & (r > wob - 0.12)
    out[edge, :3] = hexc(DIRT[3])
    return Image.fromarray(out, "RGBA")


def grass_tuft(seed):
    rng = random.Random(seed)
    im = Image.new("RGBA", (16, 24))
    d = ImageDraw.Draw(im)
    for i in range(rng.randint(5, 8)):
        x0 = 8 + rng.randint(-3, 3)
        hgt = rng.randint(9, 20)
        lean = rng.uniform(-5, 5)
        cols = [GRASS[5], GRASS[4], GRASS[2], GRASS[0]]
        for k in range(hgt):
            t = k / hgt
            x = int(round(x0 + lean * t * t))
            y = 23 - k
            c = cols[min(3, int(t * 4))]
            d.point((x, y), fill=c)
            if k < hgt * 0.4:
                d.point((x + 1, y), fill=GRASS[4])
    return im


def flower(kind):
    petal = {"daisy": "#ffffff", "poppy": "#e04848", "corn": "#5ea0ff", "butter": "#ffd25e",
             "lavender": "#a07ad0", "marigold": "#ff9a3a"}[kind]
    im = Image.new("RGBA", (16, 16))
    d = ImageDraw.Draw(im)
    d.line([(8, 15), (8, 7)], fill=GRASS[4])
    d.point((7, 11), fill=GRASS[2])
    d.point((9, 12), fill=GRASS[2])
    if kind == "lavender":
        for y in range(2, 8):
            d.point((8 + (y % 2), y), fill=petal)
            d.point((7 + (y % 2), y), fill="#6a4aa0")
    else:
        for dx, dy in ((0, -2), (-2, 0), (2, 0), (0, 2), (-1, -1), (1, -1), (-1, 1), (1, 1)):
            d.point((8 + dx, 5 + dy), fill=petal)
        d.point((8, 5), fill="#ffd25e" if kind != "butter" else "#e8a93a")
    # 1px koyu dış çizgi
    return outline(im, "#1d4428")


def outline(im, color):
    a = np.array(im)
    alpha = a[..., 3] > 0
    grow = np.zeros_like(alpha)
    for dy, dx in ((0, 1), (1, 0), (0, -1), (-1, 0)):
        grow |= np.roll(np.roll(alpha, dy, 0), dx, 1)
    ring = grow & ~alpha
    a[ring, :3] = hexc(color)
    a[ring, 3] = 255
    return Image.fromarray(a, "RGBA")


def shadow(w, h):
    y, x = np.mgrid[0:h, 0:w]
    r = ((x + 0.5 - w / 2) / (w / 2)) ** 2 + ((y + 0.5 - h / 2) / (h / 2)) ** 2
    a = np.where(r < 1, np.where(r < 0.55, 90, 55), 0).astype(np.uint8)
    out = np.zeros((h, w, 4), np.uint8)
    out[..., :3] = hexc("#172238")
    out[..., 3] = a
    return Image.fromarray(out, "RGBA")


