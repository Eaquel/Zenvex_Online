def icon(name):
    rows = [r for r in ICONS[name].strip("\n").split("\n")]
    light, base, shade = ICON_COLORS.get(name, ICON_COLORS["default"])
    cmap = {"#": hexc("#1b1c26"), "a": hexc(base), "b": hexc(light), "c": hexc(shade)}
    a = np.zeros((16, 16, 4), np.uint8)
    for y, row in enumerate(rows[:16]):
        for x, ch in enumerate(row[:16]):
            if ch in cmap:
                a[y, x, :3] = cmap[ch]
                a[y, x, 3] = 255
    return Image.fromarray(a, "RGBA")


def pixelate_bg(path, out, w=320, h=180, colors=48):
    """Yapay zeka arka planını pixel art'a çevirir (küçült + palet)."""
    im = Image.open(path).convert("RGB")
    W, H = im.size
    im = im.crop((0, 0, W, int(H * 0.94)))  # filigranlı alt şeridi kes
    im = im.resize((w, h), Image.LANCZOS)
    im = im.quantize(colors=colors, method=Image.MEDIANCUT, dither=Image.Dither.NONE).convert("RGB")
    im.save(out)
    return im
