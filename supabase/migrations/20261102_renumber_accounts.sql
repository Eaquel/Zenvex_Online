-- 0 yönetici aynı kaldı. Hesaba bağlı tüm yabancı anahtarlar ON UPDATE CASCADE yapıldı ki ID değişince izlesinler;
-- FK'sız Sezon Bileti tabloları elle güncellenir. Sonraki yeni hesap en büyük ID + 1'den başlar.
do $$
declare r record;
begin
  for r in select conname, conrelid::regclass as tbl, pg_get_constraintdef(oid) as def
           from pg_constraint where contype = 'f' and confrelid = 'public.accounts'::regclass and confupdtype <> 'c' loop
    execute format('alter table %s drop constraint %I', r.tbl, r.conname);
    execute format('alter table %s add constraint %I %s on update cascade', r.tbl, r.conname, r.def);
  end loop;
end $$;

alter table public.accounts alter column id set generated by default;
do $$
declare r record; n bigint := 0;
begin
  for r in select id from public.accounts where id <> 0 order by created_at, id loop
    n := n + 1;
    if r.id <> n then
      update public.accounts set id = n where id = r.id;
      update public.pass_owned set account_id = n where account_id = r.id;
      update public.pass_claims set account_id = n where account_id = r.id;
    end if;
  end loop;
  execute format('alter table public.accounts alter column id restart with %s', n + 1);
end $$;
alter table public.accounts alter column id set generated always;
